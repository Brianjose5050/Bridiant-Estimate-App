#!/usr/bin/env node
// Generates apps/server/src/admin/assets.generated.ts from the panel stylesheet and the shared brand tokens.
// Workers have no filesystem, so the styles are compiled into the bundle. Single source: the .css files.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('..', import.meta.url));
const admin = readFileSync(`${root}apps/server/static/admin.css`, 'utf8');
const tokens = readFileSync(`${root}packages/ui/src/tokens.css`, 'utf8');
const out = `// GENERATED by scripts/build-admin-assets.mjs. Do not edit by hand.
export const ADMIN_CSS = ${JSON.stringify(admin)};
export const TOKENS_CSS = ${JSON.stringify(tokens)};
`;
writeFileSync(`${root}apps/server/src/admin/assets.generated.ts`, out);
console.log('admin assets generated');
